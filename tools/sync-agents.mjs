// Builds .claude/agents/binly-builder.md = tools/agents/binly-builder.base.md + the docs every builder always needs
// (BUILDER, Binly mindset, PLAYBOOK §4–§5, TOOLS, KIT-INDEX) embedded verbatim.
// Why: every builder then starts from an IDENTICAL system prompt → shared prompt cache across builders (cheap cache
// reads instead of re-reading files), and no tool turns spent opening those docs.
// Run after editing any of those docs (tools/kitdoc.mjs runs it automatically). Takes effect in NEW sessions.
import fs from 'node:fs';
import path from 'node:path';
import {ROOT} from './lib/render.mjs';

const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8').trim();
const playbook = read('docs/PLAYBOOK.md');
const s4 = playbook.indexOf('## 4.');
const s6 = playbook.indexOf('## 6.');
const look = s4 >= 0 ? playbook.slice(s4, s6 > s4 ? s6 : undefined).trim() : playbook;
const parts = [
  ['docs/BUILDER.md — builder handbook', read('docs/BUILDER.md')],
  ['docs/RETENTION.md — the Binly mindset', read('docs/RETENTION.md')],
  ['docs/PLAYBOOK.md §4–§5 — look & motion rules', look],
  ['docs/TOOLS.md — what is installed', read('docs/TOOLS.md')],
  ['docs/KIT-INDEX.md — kit index (open only the sections you need)', read('docs/KIT-INDEX.md')],
];
const base = read('tools/agents/binly-builder.base.md');
const out = `${base}\n\n<!-- GENERATED by tools/sync-agents.mjs — edit tools/agents/binly-builder.base.md or the docs, not this file. -->\n\n${parts
  .map(([title, text]) => `=== EMBEDDED: ${title} ===\n\n${text.replace(/^# /gm, '### ')}`)
  .join('\n\n')}\n`;
fs.writeFileSync(path.join(ROOT, '.claude', 'agents', 'binly-builder.md'), out);
console.log(`.claude/agents/binly-builder.md regenerated (${(out.length / 1024).toFixed(1)} KB, embeds ${parts.length} docs)`);
