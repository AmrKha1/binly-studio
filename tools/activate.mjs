// Points the Main composition (and contact sheets / previews) at one video.
//   node tools/activate.mjs <slug>
import fs from 'node:fs';
import path from 'node:path';
import {ROOT} from './lib/render.mjs';

const slug = process.argv[2];
const quiet = process.argv.includes('--quiet');
if (!slug || !fs.existsSync(path.join(ROOT, 'src', 'videos', slug, 'index.tsx'))) {
  console.log(`usage: node tools/activate.mjs <slug>   (src/videos/<slug>/index.tsx must exist)`);
  process.exit(1);
}
fs.writeFileSync(path.join(ROOT, 'src', 'active.ts'), `// GENERATED by tools/activate.mjs — points the Main composition at one video.\nexport {active} from './videos/${slug}';\n`);
// Live-preview audio: ONLY the active video's voiceover lives in public/_active/ (the bundler copies public/ on every
// render — keeping every video's audio there would make stills slower and slower as the channel grows).
const act = path.join(ROOT, 'public', '_active');
fs.rmSync(act, {recursive: true, force: true});
const vdir = path.join(ROOT, 'videos', slug);
const vo = fs.existsSync(vdir) ? fs.readdirSync(vdir).find((f) => /^voiceover./.test(f)) : null;
if (vo && !process.env.CI) {
  fs.mkdirSync(act, {recursive: true});
  fs.copyFileSync(path.join(vdir, vo), path.join(act, vo));
}
if (!quiet) console.log(`active video: ${slug}`);
