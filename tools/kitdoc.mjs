// Rebuilds docs/KIT.md (the API reference builders read) from docs/kit/*.md.
import fs from 'node:fs';
import path from 'node:path';
import {ROOT} from './lib/render.mjs';

const dir = path.join(ROOT, 'docs', 'kit');
const order = ['core.md', 'text-cards-diagrams.md'];
const files = [...order.filter((f) => fs.existsSync(path.join(dir, f))), ...fs.readdirSync(dir).filter((f) => f.endsWith('.md') && !order.includes(f)).sort()];
const body = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim()).join('\n\n---\n\n');
fs.writeFileSync(
  path.join(ROOT, 'docs', 'KIT.md'),
  `# Binly kit — API reference (generated by tools/kitdoc.mjs from docs/kit/*.md)\nImport from \`../../../kit/<module>\` inside a chapter. Visual showcase: \`node tools/still.mjs --comp Gallery --props "{\\"page\\":\\"<page>\\"}" --at 4\` (pages: text cards diagrams data icons env science geo people transitions).\n\n${body}\n`
);
console.log(`docs/KIT.md ← ${files.join(', ')}`);
