// Rebuilds the kit documentation:
//   docs/KIT-INDEX.md — SHORT index (read this first): every exported component name, grouped by the doc section that
//                       explains it → open only the 1–3 sections you need (progressive disclosure, saves tokens).
//   docs/KIT.md       — everything concatenated (for humans / rare full reads).
// Then refreshes the builder agent definition (tools/sync-agents.mjs).
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {ROOT} from './lib/render.mjs';

const dir = path.join(ROOT, 'docs', 'kit');
const order = ['core.md', 'text-cards-diagrams.md'];
const files = [...order.filter((f) => fs.existsSync(path.join(dir, f))), ...fs.readdirSync(dir).filter((f) => f.endsWith('.md') && !order.includes(f)).sort()];
const body = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim()).join('\n\n---\n\n');
fs.writeFileSync(
  path.join(ROOT, 'docs', 'KIT.md'),
  `# Binly kit — full API reference (generated by tools/kitdoc.mjs from docs/kit/*.md)\nPrefer docs/KIT-INDEX.md + the 1–3 sections you need. Visual catalogs: docs/catalog/templates.png, docs/catalog/kit.png.\n\n${body}\n`
);

// which source modules each doc section covers + one-line purpose
const SECTIONS = [
  ['core.md', ['stage', 'anim', 'shots', 'theme', 'video'], 'Stage, camera (Cam/World/breathe/shake), time maths (ramp/keys/win/camAt/rand/noise1/countUp), Shots + transitions, palette C/SEM'],
  ['text-cards-diagrams.md', ['text', 'cards', 'diagrams', 'fx', 'people'], 'Typography, paper objects & screens & bubbles, diagrams/arrows/flows, light & motion fx, characters (Person/Crowd)'],
  ['templates.md', ['templates'], 'Ready-made full shots for standard beats (stat, quote, evidence, claim, compare, list, timeline, map, person, process, question, title)'],
  ['archival.md', ['archival'], 'Real-image shots edited like a top YouTube storyteller (Ken Burns, detail hunt, montage, collage, compare, document scan, annotated, in-world, parallax)'],
  ['photo.md', ['photo'], 'Photo/PhotoMark components + how to find free images (tools/photo.mjs)'],
  ['data.md', ['data'], 'Charts & exact-number visuals'],
  ['icons.md', ['icons'], '64 flat pictogram icons'],
  ['env.md', ['env'], 'Environments (sky, landscape, cities, streets, rooms, bathhouse, lab, museum, study, bedroom, mind space) and props'],
  ['science.md', ['science'], 'Brain, head, body, organs, eye, cells, germs, DNA, molecules, waveforms, electrodes'],
  ['geo.md', ['geo'], 'Flat maps (GeoMap), pins, routes, spread rings'],
  ['silhouette.md', ['silhouette'], 'Shared library of free organism silhouettes (animals, dinosaurs, microbes…) — recolourable, dashed = inferred'],
  ['depth.md', ['depth'], '"Looks 3D" drawn flat: Globe, isometric buildings/rooms/props, shaded spheres, DepthStack'],
];
const exportsOf = (mod) => {
  const f = path.join(ROOT, 'src', 'kit', `${mod}.tsx`);
  const g = fs.existsSync(f) ? f : path.join(ROOT, 'src', 'kit', `${mod}.ts`);
  if (!fs.existsSync(g)) return [];
  const src = fs.readFileSync(g, 'utf8');
  return [...new Set([...src.matchAll(/^export (?:const|function|type) (\w+)/gm)].map((m) => m[1]))];
};
const lines = ['# Kit index — read this first, then open ONLY the sections you need', '', 'Import from `../../../kit/<module>` (chapters) · visual catalogs: `docs/catalog/templates.png`, `docs/catalog/kit.png` · full reference: `docs/KIT.md` (rarely needed).', ''];
for (const [doc, mods, purpose] of SECTIONS) {
  if (!fs.existsSync(path.join(dir, doc))) continue;
  const names = mods.flatMap((m) => exportsOf(m).map((n) => n));
  lines.push(`## docs/kit/${doc} — ${purpose}`);
  lines.push(`modules: ${mods.map((m) => `kit/${m}`).join(', ')}`);
  lines.push(names.join(', '));
  lines.push('');
}
fs.writeFileSync(path.join(ROOT, 'docs', 'KIT-INDEX.md'), lines.join('\n'));
console.log(`docs/KIT.md ← ${files.join(', ')}\ndocs/KIT-INDEX.md (${(fs.statSync(path.join(ROOT, 'docs', 'KIT-INDEX.md')).size / 1024).toFixed(1)} KB)`);
const sync = path.join(ROOT, 'tools', 'sync-agents.mjs');
if (fs.existsSync(sync)) spawnSync(process.execPath, [sync], {stdio: 'inherit'});
