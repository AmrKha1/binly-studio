// Free organism silhouettes from PhyloPic (animals, dinosaurs, humans, plants, microbes…) → a SHARED library that every
// video reuses (src/assets/silhouettes/). Only free licences (public domain / CC0 / CC BY / CC BY-SA); credits automatic.
//   node tools/silhouette.mjs list                         → what's already in the library (reuse first!)
//   node tools/silhouette.mjs search "tyrannosaurus" [--n 8]   → .cache/silhouettes/search.png (numbered) + list
//   node tools/silhouette.mjs get <#> --as trex            → src/assets/silhouettes/trex.json (+ registry, + credit)
// Use: <Silhouette name="trex" x={960} y={900} h={420} color={C.ink} …/>  (kit/silhouette — recolourable, animatable)
import fs from 'node:fs';
import path from 'node:path';
import {ROOT, args, done, stills} from './lib/render.mjs';

const UA = {headers: {'User-Agent': 'BinlyStudio/1.0 (https://github.com/AmrKha1/binly-studio)'}};
const API = 'https://api.phylopic.org';
const LIB = path.join(ROOT, 'src', 'assets', 'silhouettes');
const cache = path.join(ROOT, '.cache', 'silhouettes');
fs.mkdirSync(LIB, {recursive: true});
fs.mkdirSync(cache, {recursive: true});
const a = args();
const [cmd, q] = a._;
const active = fs.readFileSync(path.join(ROOT, 'src', 'active.ts'), 'utf8').match(/videos\/([^']+)'/)?.[1];
const slug = a.slug ?? active;
const getJson = async (u) => {
  const r = await fetch(u.startsWith('http') ? u : API + u, UA);
  if (!r.ok) throw new Error(`PhyloPic ${r.status} for ${u}`);
  return r.json();
};
const licenceOf = (href = '') => {
  const h = href.toLowerCase();
  if (/-nc|-nd|noncommercial|noderiv/.test(h)) return null;
  if (/publicdomain|\/zero\/|cc0/.test(h)) return 'Public domain (CC0/PDM)';
  const m = h.match(/licenses\/(by(?:-sa)?)\/(\d\.\d)/);
  return m ? `CC ${m[1].toUpperCase()} ${m[2]}` : null;
};

function writeRegistry() {
  const items = fs.readdirSync(LIB).filter((f) => f.endsWith('.json')).map((f) => f.replace('.json', '')).sort();
  const id = (n) => '_' + n.replace(/[^\w]/g, '_');
  fs.writeFileSync(
    path.join(LIB, 'index.ts'),
    `// GENERATED by tools/silhouette.mjs — the shared silhouette library (reused by every video).\n${items.map((n) => `import ${id(n)} from './${n}.json';`).join('\n')}\n\nexport type SilhouetteData = {name: string; viewBox: [number, number]; markup: string; credit: {author: string; licence: string; source: string}; title: string};\nexport const SILHOUETTES: Record<string, SilhouetteData> = {\n${items.map((n) => `  ${JSON.stringify(n)}: ${id(n)} as SilhouetteData,`).join('\n')}\n};\n`
  );
  return items;
}

async function search() {
  const {build} = await getJson('/');
  const n = Number(a.n ?? 8);
  const tryName = async (name) => (await getJson(`/images?build=${build}&filter_name=${encodeURIComponent(name.toLowerCase())}&embed_items=true&page=0`))._embedded?.items ?? [];
  let items = await tryName(q);
  let matched = q;
  if (!items.length) {
    const ac = await getJson(`/autocomplete?build=${build}&query=${encodeURIComponent(q.toLowerCase())}`);
    for (const name of (ac.matches ?? []).slice(0, 4)) {
      items = await tryName(name);
      if (items.length) {
        matched = name;
        break;
      }
    }
  }
  const ok = items
    .map((it) => ({uuid: it.uuid, title: it._links.specificNode?.title ?? it._links.nodes?.[0]?.title ?? matched, licence: licenceOf(it._links.license?.href), author: it._links.contributor?.title ?? 'PhyloPic contributor', vector: it._links.vectorFile?.href, thumb: it._links.rasterFiles?.slice(-1)[0]?.href, page: `https://www.phylopic.org/images/${it.uuid}`}))
    .filter((x) => x.licence && x.vector && x.thumb)
    .slice(0, n);
  if (!ok.length) {
    console.log(`no free-licence silhouettes for "${q}" (try the scientific or common name, e.g. "canis lupus", "homo sapiens", "bacillus").`);
    return;
  }
  fs.writeFileSync(path.join(cache, 'last-search.json'), JSON.stringify(ok, null, 1));
  const imgs = [];
  for (const c of ok) {
    const b = Buffer.from(await (await fetch(c.thumb, UA)).arrayBuffer());
    imgs.push(`data:image/png;base64,${b.toString('base64')}`);
  }
  await stills({id: 'Grid', props: {images: imgs, labels: ok.map((_, i) => `#${i + 1}`), cols: Math.min(4, ok.length), fit: 'contain'}, frames: [0], outFiles: [path.join(cache, 'search.png')], quiet: true});
  await done();
  ok.forEach((c, i) => console.log(`#${i + 1}  ${c.title}  [${c.licence}]  by ${c.author}`));
  console.log(`\nsheet: .cache/silhouettes/search.png → node tools/silhouette.mjs get <#> --as <name>`);
}

async function get() {
  const name = (a.as ?? '').toLowerCase().replace(/[^\w-]/g, '');
  if (!name) throw new Error('give a short name: --as trex');
  const last = JSON.parse(fs.readFileSync(path.join(cache, 'last-search.json'), 'utf8'));
  const c = last[Number(String(q).replace('#', '')) - 1];
  if (!c) throw new Error(`no result #${q} in the last search`);
  const svg = await (await fetch(c.vector, UA)).text();
  const vb = svg.match(/viewBox="([\d.\s-]+)"/)?.[1]?.trim().split(/\s+/).map(Number);
  const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1] ?? '';
  const markup = inner
    .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
    .replace(/\s(fill|stroke)="[^"]*"/g, '')
    .replace(/<path /g, '<path vector-effect="non-scaling-stroke" ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!vb || vb.length !== 4 || !markup.includes('<path')) throw new Error('unexpected SVG format — pick another result');
  const data = {name, title: c.title, viewBox: [vb[2], vb[3]], markup, credit: {author: c.author, licence: c.licence, source: c.page}};
  fs.writeFileSync(path.join(LIB, `${name}.json`), JSON.stringify(data));
  const items = writeRegistry();
  // credit for the active video (upload-pack also collects credits of silhouettes a video uses)
  if (slug && slug !== '_empty' && fs.existsSync(path.join(ROOT, 'videos', slug))) {
    const cf = path.join(ROOT, 'videos', slug, 'credits.json');
    const creds = fs.existsSync(cf) ? JSON.parse(fs.readFileSync(cf, 'utf8')) : [];
    if (!creds.some((x) => x.file === `silhouette:${name}`)) creds.push({file: `silhouette:${name}`, title: `${c.title} silhouette`, author: c.author, licence: c.licence, source: c.page});
    fs.writeFileSync(cf, JSON.stringify(creds, null, 1));
  }
  console.log(`saved silhouette "${name}" (${c.title}, ${c.licence}, by ${c.author}) · library: ${items.length} silhouettes\nuse: <Silhouette name="${name}" x={…} y={…} h={…} color={C.ink} />`);
}

function list() {
  const items = writeRegistry();
  if (!items.length) return console.log('silhouette library is empty');
  for (const n of items) {
    const d = JSON.parse(fs.readFileSync(path.join(LIB, `${n}.json`), 'utf8'));
    console.log(`${n.padEnd(16)} ${d.title} · ${d.credit.licence}`);
  }
}

try {
  if (cmd === 'search' && q) await search();
  else if (cmd === 'get' && q) await get();
  else if (cmd === 'list') list();
  else console.log('usage: node tools/silhouette.mjs list | search "name" [--n 8] | get <#> --as <name>');
} catch (e) {
  console.log(`silhouette: ${e.message}`);
  await done();
  process.exit(1);
}
