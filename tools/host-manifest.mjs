// Scans public/_hosts/<who>/*.png and writes src/kit/host-images.ts (pose names + pixel sizes) so the kit's ImageHost
// knows every pose without reading files at render time. Run after adding/replacing host pose images.
//   node tools/host-manifest.mjs
import fs from 'node:fs';
import path from 'node:path';
import {ROOT} from './lib/render.mjs';

const dir = path.join(ROOT, 'public', '_hosts');
const out = {};
for (const who of fs.existsSync(dir) ? fs.readdirSync(dir) : []) {
  const d = path.join(dir, who);
  if (!fs.statSync(d).isDirectory()) continue;
  out[who] = {};
  for (const f of fs.readdirSync(d).filter((x) => x.endsWith('.png')).sort()) {
    const b = fs.readFileSync(path.join(d, f));
    out[who][f.replace(/\.png$/, '')] = [b.readUInt32BE(16), b.readUInt32BE(20)];
  }
}
const file = path.join(ROOT, 'src', 'kit', 'host-images.ts');
fs.writeFileSync(file, `// GENERATED by tools/host-manifest.mjs — host pose images in public/_hosts/<who>/<pose>.png: [width, height] px.\n// Poses named full-* are FULL BODY (feet at the bottom edge); all others are waist-up (cut at the waist).\nexport const HOST_IMAGES = ${JSON.stringify(out, null, 1)} as const;\nexport type HostImageWho = keyof typeof HOST_IMAGES;\n`);
console.log(Object.entries(out).map(([w, p]) => `${w}: ${Object.keys(p).length} poses`).join(' · ') + ` → ${path.relative(ROOT, file)}`);
