// Writes src/videos/<slug>/speech.ts — the narrator's word intervals, so the host's mouth (kit/host) moves exactly
// while words are spoken:  import {WORDS} from '../speech';  <Host … talk={talkFrom(t, WORDS)} />
//   node tools/speech-map.mjs [--slug s]     (new-video.mjs runs it after timing; safe to re-run)
import fs from 'node:fs';
import path from 'node:path';
import {ROOT, args} from './lib/render.mjs';

const a = args();
const slug = a.slug ?? fs.readFileSync(path.join(ROOT, 'src', 'active.ts'), 'utf8').match(/videos\/([^']+)'/)?.[1];
const wf = path.join(ROOT, 'videos', slug, 'timing', 'words.json');
if (!fs.existsSync(wf)) {
  console.log(`no timing yet (${path.relative(ROOT, wf)}) — run the timing analysis first`);
  process.exit(0);
}
const words = JSON.parse(fs.readFileSync(wf, 'utf8'));
// merge words closer than 0.06 s (one continuous mouth movement) and drop impossible spans
const iv = [];
for (const w of words) {
  if (typeof w.s !== 'number' || typeof w.e !== 'number' || w.e <= w.s) continue;
  const s = Math.round(w.s * 100) / 100;
  const e = Math.round(Math.min(w.e, w.s + 1.2) * 100) / 100; // a long "word" is usually a pause glued on
  const last = iv[iv.length - 1];
  if (last && s - last[1] < 0.06) last[1] = Math.max(last[1], e);
  else iv.push([s, e]);
}
const out = path.join(ROOT, 'src', 'videos', slug, 'speech.ts');
fs.mkdirSync(path.dirname(out), {recursive: true});
const spoken = words.filter((w) => typeof w.s === 'number' && w.w).map((w) => [Math.round(w.s * 100) / 100, Math.round(w.e * 100) / 100, String(w.w)]);
fs.writeFileSync(out, `// GENERATED by tools/speech-map.mjs from videos/${slug}/timing/words.json.\n// WORDS = speaking intervals (mouth) · SPOKEN = [start, end, word] for SayPop (key phrases only — never subtitles).\nexport const WORDS: [number, number][] = ${JSON.stringify(iv)};\nexport const SPOKEN: [number, number, string][] = ${JSON.stringify(spoken)};\n`);
console.log(`speech map: ${iv.length} spoken intervals → ${path.relative(ROOT, out)}`);
