// (Re)generates src/videos/<slug>/index.tsx from videos/<slug>/chapters.json and creates placeholder
// chapter files that don't exist yet. NEVER overwrites an existing chapter file.
//   node tools/scaffold.mjs <slug>
// chapters.json: [{"id":"C01","start":0,"end":92.4,"title":"The contradiction","in":{"kind":"fade"}}, ...]
import fs from 'node:fs';
import path from 'node:path';
import {ROOT} from './lib/render.mjs';

const slug = process.argv[2];
const vdir = path.join(ROOT, 'videos', slug);
const sdir = path.join(ROOT, 'src', 'videos', slug);
const chapters = JSON.parse(fs.readFileSync(path.join(vdir, 'chapters.json'), 'utf8'));
fs.mkdirSync(path.join(sdir, 'chapters'), {recursive: true});
fs.mkdirSync(path.join(sdir, 'shared'), {recursive: true});

let created = 0;
for (const c of chapters) {
  const f = path.join(sdir, 'chapters', `${c.id}.tsx`);
  if (fs.existsSync(f)) continue;
  fs.writeFileSync(
    f,
    `import React from 'react';
import {Stage} from '../../../kit/stage';
import {TitleCard} from '../../../kit/text';
import {C} from '../../../kit/theme';

// ${c.id} · ${c.start.toFixed(2)}–${c.end.toFixed(2)} s · "${c.title ?? ''}" — PLACEHOLDER (not built yet)
export const ${c.id}: React.FC<{t: number}> = ({t}) => (
  <Stage bg={C.paperShade}>
    <TitleCard kicker="placeholder · ${c.id}" title={${JSON.stringify(c.title ?? c.id)}} p={1} size={64} />
    <text x={960} y={760} textAnchor="middle" fontFamily="Inter" fontSize={36} fill={C.inkMute}>{t.toFixed(1)} s</text>
  </Stage>
);
`
  );
  created++;
}

const imports = chapters.map((c) => `import {${c.id}} from './chapters/${c.id}';`).join('\n');
const list = chapters
  .map((c) => `  {id: '${c.id}', start: ${c.start}, end: ${c.end}, C: ${c.id}${c.in ? `, in: ${JSON.stringify(c.in)}` : ''}},`)
  .join('\n');
fs.writeFileSync(
  path.join(sdir, 'index.tsx'),
  `// GENERATED by tools/scaffold.mjs from videos/${slug}/chapters.json — edit chapters.json, then re-run scaffold.
import React from 'react';
import {Chapters, ChapterDef, VideoModule} from '../../kit/video';
import {Stage} from '../../kit/stage';
import META from '../../../videos/${slug}/video.json';
${imports}

export const CHAPTERS: ChapterDef[] = [
${list}
];

const Video: React.FC<{t: number}> = ({t}) => (CHAPTERS.length ? <Chapters t={t} chapters={CHAPTERS} /> : <Stage />);

export const active: VideoModule = {meta: {slug: META.slug, title: META.title, duration: META.duration, audio: META.audio, lang: (META as {lang?: string}).lang}, Video};
`
);
console.log(`scaffold: ${chapters.length} chapter(s) in index.tsx, ${created} placeholder file(s) created`);
